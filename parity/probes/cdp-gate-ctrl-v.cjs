// Native clipboard regression; isolated engine, shell and Chrome only. Mac host uses CDP Paste command.
const { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync, realpathSync } = require('node:fs');
const { spawn } = require('node:child_process');
const { join } = require('node:path');
const { tmpdir } = require('node:os');
const { HeadlessServer } = require('../../src/server.js');
const WebSocket = require('ws');
const sleep = ms => new Promise(r => setTimeout(r, ms));
const out = process.env.GATE_OUT || '/tmp/clideck-ctrl-v-ui';
mkdirSync(out, { recursive: true });
let fails = 0, passes = 0;
const check = (name, yes, detail) => { yes ? passes++ : fails++; console.log(`${yes ? 'PASS' : 'FAIL'} ${name}${detail === undefined ? '' : ' ' + JSON.stringify(detail)}`); };
(async () => {
  const dataDir = mkdtempSync(join(tmpdir(), 'ctrl-v-data-'));
  const cwd = realpathSync(mkdtempSync(join(tmpdir(), 'ctrl-v-files-')));
  writeFileSync(join(dataDir, 'config.json'), JSON.stringify({ onboarding: { completed: true, seenTips: ['guided-tour', 'about-me'] } }));
  const server = new HeadlessServer({ port: 0, dataDir });
  let chrome, ctl, cws;
  try {
    const address = await server.listen(), base = `http://127.0.0.1:${address.port}`;
    ctl = new WebSocket(base.replace('http:', 'ws:'));
    const events = [];
    ctl.on('message', raw => { try { events.push(JSON.parse(raw)); } catch {} });
    await new Promise(r => ctl.on('open', r));
    ctl.send(JSON.stringify({ type: 'session.create', provider: 'shell', name: 'links', cwd }));
    for (let i=0; i<100 && !events.some(e=>e.type==='session.created'); i++) await sleep(100);
    const sid = events.find(e=>e.type==='session.created').sessionId;
    const profile = mkdtempSync(join(tmpdir(), 'ctrl-v-chrome-'));
    chrome = spawn('/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', ['--headless=new', '--disable-gpu', '--remote-debugging-port=0', `--user-data-dir=${profile}`, '--no-first-run', 'about:blank'], { stdio: 'ignore' });
    const portFile = join(profile, 'DevToolsActivePort');
    for (let i=0; i<100 && !existsSync(portFile); i++) await sleep(100);
    const port = readFileSync(portFile, 'utf8').split('\n')[0];
    const target = await (await fetch(`http://127.0.0.1:${port}/json/new?about:blank`, {method:'PUT'})).json();
    cws = new WebSocket(target.webSocketDebuggerUrl);
    await new Promise(r=>cws.on('open',r));
    let seq=0; const pending=new Map();
    cws.on('message', raw=> {const m=JSON.parse(raw);if(pending.has(m.id)){pending.get(m.id)(m);pending.delete(m.id);}});
    const cmd=(method,params={})=>new Promise((resolve,reject)=>{const id=++seq;const timer=setTimeout(()=>{pending.delete(id);reject(new Error(method+' timeout'));},12000);pending.set(id,m=>{clearTimeout(timer);m.error?reject(new Error(JSON.stringify(m.error))):resolve(m.result);});cws.send(JSON.stringify({id,method,params}));});
    const js=async expression=>{const r=await cmd('Runtime.evaluate',{expression,returnByValue:true,awaitPromise:true});if(r.exceptionDetails)throw new Error(JSON.stringify(r.exceptionDetails));return r.result?.value;};
    const snap=async name=>{const s=await cmd('Page.captureScreenshot',{format:'png'});writeFileSync(join(out,name),Buffer.from(s.data,'base64'));};
    await cmd('Emulation.setDeviceMetricsOverride',{width:1440,height:900,deviceScaleFactor:1,mobile:false});
    await cmd('Page.enable');await cmd('Emulation.setFocusEmulationEnabled',{enabled:true});
    await cmd('Emulation.setUserAgentOverride',{userAgent:'Mozilla/5.0 Chrome/140.0.0.0 Safari/537.36',platform:'Linux x86_64'});
    await cmd('Page.navigate',{url:base});await sleep(2200);
    await js(`(async()=>{window.store=(await import('/js/store.js')).store;store.select(${JSON.stringify(sid)});window.tm=await import('/js/ui/terminal.js');window.term=tm.__termForTest();window.sent=[];const send=WebSocket.prototype.send;WebSocket.prototype.send=function(data){try{sent.push(JSON.parse(data))}catch{}return send.call(this,data)};})()`);
    const input = () => js(`sent.filter(e=>e.type==='input').map(e=>e.data)`);
    const key = async (modifiers=2, nativePaste=false) => {
      await cmd('Input.dispatchKeyEvent',{type:'keyDown',key:'v',code:'KeyV',windowsVirtualKeyCode:86,modifiers,...(nativePaste?{commands:['paste']}:{})});
      await cmd('Input.dispatchKeyEvent',{type:'keyUp',key:'v',code:'KeyV',windowsVirtualKeyCode:86,modifiers});await sleep(150);
    };
    await js(`term.focus();sent=[]`);await key();
    check('default Ctrl+V sends terminal literal control',JSON.stringify(await input())===JSON.stringify(['\x16']));
    await js(`(async()=>{window.settings=await import('/js/ui/settings.js');settings.openSettingsAt('general');document.querySelector('[aria-label="Paste with Ctrl+V"]').click()})()`);
    check('setting persists enabled',await js(`localStorage.getItem('clideck.ctrlVPaste')==='true'`));
    for(const theme of ['dark','light']) {
      await js(`(async()=>{(await import('/js/theme.js')).setThemePref('${theme}');document.querySelector('[data-sec="behavior"]').scrollIntoView({block:'center'})})()`);await sleep(300);await snap('ctrl-v-'+theme+'.png');
    }
    await cmd('Emulation.setDeviceMetricsOverride',{width:420,height:800,deviceScaleFactor:1,mobile:false});await sleep(150);await snap('ctrl-v-narrow.png');
    check('narrow settings has no horizontal overflow',await js(`document.querySelector('.set-body').scrollWidth<=document.querySelector('.set-body').clientWidth`));
    await cmd('Emulation.setDeviceMetricsOverride',{width:1440,height:900,deviceScaleFactor:1,mobile:false});
    await js(`settings.closeSettings();term.focus();sent=[]`);await key();
    check('enabled Ctrl+V emits no literal control',!(await input()).includes('\x16'));
    await cmd('Browser.grantPermissions',{origin:base,permissions:['clipboardReadWrite','clipboardSanitizedWrite']});
    await js(`navigator.clipboard.writeText('first line\\nsecond line')`);
    await js(`store.active().bracketedPaste=true;sent=[];term.focus()`);
    // The test host is macOS: invoke Chrome's native Paste edit command with the Linux shortcut.
    await key(2,true);
    check('native paste uses existing single multiline transaction',JSON.stringify(await input())===JSON.stringify(['\x1b[200~first line\nsecond line\x1b[201~']),await input());
    await js(`sent=[];term.focus()`);await key(10,true);
    check('Ctrl+Shift+V still reaches native paste',JSON.stringify(await input())===JSON.stringify(['\x1b[200~first line\nsecond line\x1b[201~']));
    await js(`navigator.clipboard.writeText('')`);await js(`sent=[];term.focus()`);await key(2,true);
    check('empty clipboard adds no text or literal Ctrl+V',(await input()).every(s=>s===''||s==='\x1b[200~\x1b[201~'),await input());
    await js(`settings.openSettingsAt('general');const e=document.querySelector('[data-sec="about"] input');e.focus();window.before=e.value;sent=[]`);
    await key(2,true);check('settings focus cannot paste into terminal',!(await input()).length);
    await js(`settings.closeSettings()`);await cmd('Page.reload');await sleep(1700);
    check('reload retains opt-in',await js(`(async()=>{const s=await import('/js/ui/settings.js');s.openSettingsAt('general');return document.querySelector('[aria-label="Paste with Ctrl+V"]').getAttribute('aria-checked')==='true'})()`));
    await cmd('Emulation.setUserAgentOverride',{userAgent:'Mozilla/5.0 Chrome/140.0.0.0 Safari/537.36',platform:'MacIntel'});
    await cmd('Page.reload');await sleep(1700);
    await js(`(async()=>{window.settings=await import('/js/ui/settings.js');settings.openSettingsAt('general')})()`);
    check('Mac shows enabled browser setting',await js(`document.querySelector('[aria-label="Paste with Ctrl+V"]').getAttribute('aria-checked')==='true'`));
    await js(`(async()=>{settings.closeSettings();window.term=(await import('/js/ui/terminal.js')).__termForTest();window.store=(await import('/js/store.js')).store;store.active().bracketedPaste=true;window.sent=[];const old=WebSocket.prototype.send;WebSocket.prototype.send=function(data){try{sent.push(JSON.parse(data))}catch{}return old.call(this,data)};term.focus();await navigator.clipboard.writeText('Mac paste')})()`);
    await key(2);
    check('Mac bare Ctrl+V reads clipboard without native Paste command',JSON.stringify(await input())===JSON.stringify(['\x1b[200~Mac paste\x1b[201~']));
    await js(`sent=[];localStorage.setItem('clideck.ctrlVPaste','false')`);await key(2);
    check('Mac disabled Ctrl+V sends literal control',JSON.stringify(await input())===JSON.stringify(['\x16']));
    await js(`sent=[];localStorage.setItem('clideck.ctrlVPaste','true')`);
    await key(4,true);
    check('Mac Cmd+V native paste remains unchanged',JSON.stringify(await input())===JSON.stringify(['\x1b[200~Mac paste\x1b[201~']));
    await js(`window.readClipboard=navigator.clipboard.readText.bind(navigator.clipboard);navigator.clipboard.readText=()=>new Promise(r=>window.finishRead=r);sent=[];term.focus()`);
    await key(2);
    await js(`settings.openSettingsAt('general');document.querySelector('[data-sec="about"] input').focus();finishRead('stale paste')`);await sleep(100);
    check('Mac delayed clipboard cannot paste after focus moves',!(await input()).length);
    await js(`settings.closeSettings();term.focus();sent=[]`);await key(2);
    await js(`store.active().live=false;finishRead('stale paste')`);await sleep(100);
    check('Mac delayed clipboard cannot paste into stopped session',!(await input()).length);
    await js(`store.active().live=true;term.focus();sent=[]`);await key(2);
    await js(`window.originalId=store.activeId;store.sessions.set('different-session',{...store.active(),id:'different-session'});store.select('different-session');finishRead('stale paste')`);await sleep(100);
    check('Mac delayed clipboard cannot paste after session switch',!(await input()).length);
    await js(`store.select(originalId);term.focus();sent=[]`);await key(2);
    await js(`store.active().pid+=1;finishRead('stale paste')`);await sleep(100);
    check('Mac delayed clipboard cannot paste after session restart',!(await input()).length);
    await js(`store.active().live=true;term.focus();navigator.clipboard.readText=()=>Promise.reject(new Error('denied'));sent=[]`);await key(2);
    check('Mac denied clipboard reports fallback without input',!(await input()).length&&await js(`document.querySelector('.toaster').textContent.includes('Use Cmd+V')`));
    await js(`navigator.clipboard.readText=undefined;sent=[];term.focus()`);await key(2);
    check('Mac missing clipboard API reports fallback without input',!(await input()).length&&await js(`document.querySelector('.toaster').textContent.includes('Use Cmd+V')`));
    await js(`navigator.clipboard.readText=readClipboard`);
  } finally {
    cws?.close();ctl?.close();chrome?.kill();await server.close();
    console.log(`${passes} passed, ${fails} failed; captures ${out}`);process.exitCode=fails?1:0;
  }
})().catch(e=>{console.error(e);process.exitCode=1;});
