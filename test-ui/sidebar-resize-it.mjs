import assert from 'node:assert/strict';
import { installFakeDom } from './fakedom.mjs';
const dom = installFakeDom();
const handle = document.createElement('div'); handle.id = 'resize-handle'; document.body.appendChild(handle);
let captured = null;
handle.setPointerCapture = id => { captured = id; };
handle.releasePointerCapture = () => { captured = null; };
localStorage.setItem('clideck.sidebarW', '343');
const { initSidebarResize, sidebarWidth } = await import('../public/js/ui/sidebar-resize.js');
initSidebarResize();
const tip = handle.querySelector('.resize-tooltip');
const width = () => parseInt(document.documentElement.style['--sidebar-w'], 10);
const event = (clientX, pointerId = 1) => ({ clientX, clientY: 150, pointerId, button: 0, preventDefault() {} });
let checks = 0;
function check(name, fn) { fn(); checks++; console.log('PASS ' + name); }
check('saved widths remain exact until dragged; rounded tooltip uses browser width', () => { assert.equal(width(),343); assert.equal(tip.textContent,'Sessions · 29%'); });
handle._fire('pointerdown',event(346)); dom.winFire('pointermove',event(346));
check('off-center grab does not jump; pointer is captured', () => { assert.equal(width(),343); assert.equal(captured,1); });
dom.winFire('pointermove',event(359));
check('drag snaps to five-pixel widths without writing storage yet', () => { assert.equal(width(),355); assert.equal(sidebarWidth(),343); });
dom.winFire('pointermove',event(200,2));
check('another pointer cannot move this drag', () => assert.equal(width(),355));
dom.winFire('pointermove',event(346));
check('returning to the grab position restores the original width', () => assert.equal(width(),343));
dom.winFire('pointermove',event(1000));
check('maximum still clamps to560', () => assert.equal(width(),560));
dom.winFire('pointercancel',event(1000));
check('cancel keeps the displayed width, persists and releases drag listeners/capture', () => { assert.equal(sidebarWidth(),560); assert.equal(captured,null); assert.equal(document.body.classList.contains('resizing'),false); for(const name of ['pointermove','pointerup','pointercancel','blur']) assert.equal(window._on[name].length,0); });
dom.winFire('pointermove',event(250));assert.equal(width(),560);
handle._fire('pointerdown',event(559)); dom.winFire('pointermove',event(20));dom.winFire('pointerup',event(20));
check('minimum still clamps to240 and release persists', () => assert.equal(sidebarWidth(),240));
handle._fire('dblclick');
check('double click resets both display and storage to340', () => { assert.equal(width(),340); assert.equal(sidebarWidth(),340); });
window.innerWidth = 420; dom.winFire('resize');
check('window resizing updates the percent without changing saved pixels', () => { assert.equal(tip.textContent,'Sessions · 81%'); assert.equal(sidebarWidth(),340); });
console.log(`${checks}/${checks} passed`);
